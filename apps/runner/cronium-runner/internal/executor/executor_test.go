// SIGTERM must clean up the extracted work dir and exit with code 1, and the
// process must actually die (no zombie left waiting).
func TestSignalHandlerCleansUpAndExits(t *testing.T) {
	workDir := filepath.Join(t.TempDir(), "cronium-run-signal")
	if err := os.MkdirAll(workDir, 0o755); err != nil {
		t.Fatalf("failed to create work dir: %v", err)
	}
	if err := os.WriteFile(filepath.Join(workDir, "marker"), []byte("x"), 0o644); err != nil {
		t.Fatalf("failed to write marker: %v", err)
	}

	cmd := exec.Command(os.Args[0])
	cmd.Env = append(os.Environ(), signalChildEnv+"=1", signalWorkDirEnv+"="+workDir)
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatalf("failed to get stdout pipe: %v", err)
	}
	if err := cmd.Start(); err != nil {
		t.Fatalf("failed to start child: %v", err)
	}
	defer func() { _ = cmd.Process.Kill() }() // safety net on test failure

	// Wait for the child to signal that its handler is registered.
	readyCh := make(chan error, 1)
	go func() {
		scanner := bufio.NewScanner(stdout)
		for scanner.Scan() {
			if scanner.Text() == "READY" {
				readyCh <- nil
				return
			}
		}
		readyCh <- fmt.Errorf("child exited before READY: %v", scanner.Err())
	}()
	select {
	case err := <-readyCh:
		if err != nil {
			t.Fatalf("child never became ready: %v", err)
		}
	case <-time.After(10 * time.Second):
		t.Fatal("timed out waiting for child READY")
	}

	if err := cmd.Process.Signal(syscall.SIGTERM); err != nil {
		t.Fatalf("failed to send SIGTERM: %v", err)
	}

	waitCh := make(chan error, 1)
	go func() { waitCh <- cmd.Wait() }()
	select {
	case err := <-waitCh:
		exitErr, ok := err.(*exec.ExitError)
		if !ok {
			t.Fatalf("expected non-zero exit after SIGTERM, got: %v", err)
		}
		if code := exitErr.ExitCode(); code != 1 {
			t.Errorf("exit code = %d, want 1", code)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("child did not exit promptly after SIGTERM")
	}

	if _, err := os.Stat(workDir); !os.IsNotExist(err) {
		t.Errorf("work dir was not cleaned up on SIGTERM (stat err: %v)", err)
	}
}

