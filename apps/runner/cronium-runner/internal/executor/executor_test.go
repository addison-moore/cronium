type tarEntry struct {
	name    string
	content string
	mode    int64
}

// writeSignedPayload builds a tar.gz payload from entries, signs it the same
// way the orchestrator does (Ed25519ph over the SHA-512 digest), and points
// CRONIUM_VERIFY_KEY at the matching public key.
func writeSignedPayload(t *testing.T, entries []tarEntry) string {
	t.Helper()

	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for _, e := range entries {
		if err := tw.WriteHeader(&tar.Header{
			Name:     e.name,
			Mode:     e.mode,
			Size:     int64(len(e.content)),
			Typeflag: tar.TypeReg,
		}); err != nil {
			t.Fatalf("failed to write tar header: %v", err)
		}
		if _, err := tw.Write([]byte(e.content)); err != nil {
			t.Fatalf("failed to write tar content: %v", err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatalf("failed to close tar: %v", err)
	}
	if err := gz.Close(); err != nil {
		t.Fatalf("failed to close gzip: %v", err)
	}

	return signPayloadBytes(t, buf.Bytes())
}

// signPayloadBytes writes content as the payload file, signs it, and sets
// CRONIUM_VERIFY_KEY. Returns the payload path.
func signPayloadBytes(t *testing.T, content []byte) string {
	t.Helper()
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatalf("failed to generate key: %v", err)
	}
	payloadPath := filepath.Join(t.TempDir(), "payload.tar.gz")
	if err := os.WriteFile(payloadPath, content, 0o644); err != nil {
		t.Fatalf("failed to write payload: %v", err)
	}
	digest := sha512.Sum512(content)
	sig, err := priv.Sign(rand.Reader, digest[:], crypto.SHA512)
	if err != nil {
		t.Fatalf("failed to sign payload: %v", err)
	}
	if err := os.WriteFile(payloadPath+".sig", []byte(base64.StdEncoding.EncodeToString(sig)+"\n"), 0o644); err != nil {
		t.Fatalf("failed to write signature: %v", err)
	}
	t.Setenv(payload.VerifyKeyEnvVar, base64.StdEncoding.EncodeToString(pub))
	return payloadPath
}

