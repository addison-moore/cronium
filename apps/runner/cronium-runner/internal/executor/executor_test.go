func TestExecuteScriptEnvironmentPropagation(t *testing.T) {
	requireTool(t, "bash")
	t.Setenv("CRONIUM_JOB_ID", "")
	t.Setenv("CRONIUM_EXECUTION_ID", "exec-from-env")
	t.Setenv("CRONIUM_HELPER_MODE", "bundled")
	t.Setenv("CRONIUM_API_ENDPOINT", "http://127.0.0.1:1/api")
	t.Setenv("CRONIUM_API_TOKEN", "secret-token")
	t.Setenv("PARENT_VAR", "from-parent")

	e, hook := setupScript(t, types.ScriptTypeBash, "script.sh", `
echo "MANIFEST_VAR=$MANIFEST_VAR"
echo "PARENT_VAR=$PARENT_VAR"
echo "CRONIUM_JOB_ID=$CRONIUM_JOB_ID"
echo "CRONIUM_EVENT_ID=$CRONIUM_EVENT_ID"
echo "CRONIUM_EXECUTION_ID=$CRONIUM_EXECUTION_ID"
echo "CRONIUM_WORK_DIR=$CRONIUM_WORK_DIR"
echo "CRONIUM_HELPER_MODE=$CRONIUM_HELPER_MODE"
echo "CRONIUM_API_ENDPOINT=$CRONIUM_API_ENDPOINT"
echo "CRONIUM_API_TOKEN=$CRONIUM_API_TOKEN"
`)
	e.manifest.Environment = map[string]string{
		"MANIFEST_VAR": "from-manifest",
		// Manifest entries are appended after os.Environ(); os/exec keeps the
		// last duplicate, so the manifest value must win.
		"PARENT_VAR": "manifest-wins",
	}
	e.manifest.Metadata = types.Metadata{
		JobID:       "job-1",
		EventID:     "ev-1",
		ExecutionID: "exec-from-manifest", // must lose to the env var
	}

	if err := runWithWatchdog(t, e, 10*time.Second); err != nil {
		t.Fatalf("script failed: %v", err)
	}

	got := hook.streamLines("stdout")
	want := []string{
		"MANIFEST_VAR=from-manifest",
		"PARENT_VAR=manifest-wins",
		"CRONIUM_JOB_ID=job-1",
		"CRONIUM_EVENT_ID=ev-1",
		"CRONIUM_EXECUTION_ID=exec-from-env",
		"CRONIUM_WORK_DIR=" + e.workDir,
		"CRONIUM_HELPER_MODE=bundled",
		"CRONIUM_API_ENDPOINT=http://127.0.0.1:1/api",
		"CRONIUM_API_TOKEN=secret-token",
	}
	for _, line := range want {
		found := false
		for _, g := range got {
			if g == line {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("child environment missing %q; stdout = %#v", line, got)
		}
	}
}

