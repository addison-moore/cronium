// Full pipeline: verify -> extract -> manifest -> helper setup -> execute ->
// collect output -> cleanup. Requires the embedded Linux helper binaries, so
// it runs on Linux CI and is skipped elsewhere.
func TestExecuteEndToEndBash(t *testing.T) {
	if !helperBinariesEmbedded() {
		t.Skip("embedded helper binaries exist only for linux/amd64 and linux/arm64 (embed.go); SetupHelpers cannot succeed on this host")
	}
	requireTool(t, "bash")
	pinCroniumEnv(t)
	t.Setenv("CRONIUM_EXECUTION_ID", "exec-e2e")

	e, hook := newTestExecutor(t)
	t.Cleanup(func() { _ = e.Cleanup() })
	payloadPath := writeSignedPayload(t, []tarEntry{
		{name: "manifest.yaml", content: e2eManifest, mode: 0o644},
		{name: "script.sh", content: `
echo "hello-from-payload E2E_VAR=$E2E_VAR"
echo '{"msg":"hi"}' | cronium.output
`, mode: 0o755},
	})

	if err := e.Execute(payloadPath); err != nil {
		t.Fatalf("Execute failed: %v", err)
	}

	found := false
	for _, line := range hook.streamLines("stdout") {
		if line == "hello-from-payload E2E_VAR=e2e-value" {
			found = true
		}
	}
	if !found {
		t.Errorf("script output not streamed; stdout = %#v", hook.streamLines("stdout"))
	}

	// Bundled-mode scaffolding was materialized in the work dir.
	croniumDir := filepath.Join(e.workDir, ".cronium")
	for _, f := range []string{"config.json", "context.json", "variables.json", "discovery.sh",
		filepath.Join("bin", "cronium.output")} {
		if _, err := os.Stat(filepath.Join(croniumDir, f)); err != nil {
			t.Errorf("expected %s in work dir: %v", f, err)
		}
	}

	// The helper binary wrote the script's output for collection.
	outputJSON, err := os.ReadFile(filepath.Join(croniumDir, "output.json"))
	if err != nil {
		t.Fatalf("cronium.output did not write output.json: %v", err)
	}
	if !strings.Contains(string(outputJSON), `"msg": "hi"`) {
		t.Errorf("output.json = %s, want data msg=hi", outputJSON)
	}
	if !hook.hasMessageContaining("Collected helper output") {
		t.Error("expected Execute to log collected helper output")
	}

	// Cleanup removes the extraction dir.
	workDir := e.workDir
	if err := e.Cleanup(); err != nil {
		t.Fatalf("Cleanup failed: %v", err)
	}
	if _, err := os.Stat(workDir); !os.IsNotExist(err) {
		t.Errorf("work dir still exists after Cleanup (stat err: %v)", err)
	}
}

