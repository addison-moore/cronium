// TestMain re-execs the test binary as a small helper process for the signal
// handling test (setupSignalHandling calls os.Exit, so it cannot be exercised
// in-process).
func TestMain(m *testing.M) {
	if os.Getenv(signalChildEnv) == "1" {
		signalChildMain()
		return
	}
	os.Exit(m.Run())
}

// signalChildMain registers the executor's signal handler with a work
// directory and blocks until the handler terminates the process.
func signalChildMain() {
	log := logrus.New()
	log.SetOutput(io.Discard)
	e := New(log)
	e.workDir = os.Getenv(signalWorkDirEnv)
	e.setupSignalHandling()
	fmt.Println("READY")
	select {}
}

// logRecord is a captured logrus entry.
type logRecord struct {
	level   logrus.Level
	message string
	fields  map[string]interface{}
}

// captureHook records every log entry so tests can assert on streamed output.
type captureHook struct {
	mu      sync.Mutex
	records []logRecord
}

func (h *captureHook) Levels() []logrus.Level { return logrus.AllLevels }

func (h *captureHook) Fire(e *logrus.Entry) error {
	h.mu.Lock()
	defer h.mu.Unlock()
	fields := make(map[string]interface{}, len(e.Data))
	for k, v := range e.Data {
		fields[k] = v
	}
	h.records = append(h.records, logRecord{level: e.Level, message: e.Message, fields: fields})
	return nil
}

// streamLines returns the messages logged for one output stream, in order.
func (h *captureHook) streamLines(stream string) []string {
	h.mu.Lock()
	defer h.mu.Unlock()
	var out []string
	for _, r := range h.records {
		if r.fields["stream"] == stream {
			out = append(out, r.message)
		}
	}
	return out
}

func (h *captureHook) hasMessageContaining(substr string) bool {
	h.mu.Lock()
	defer h.mu.Unlock()
	for _, r := range h.records {
		if strings.Contains(r.message, substr) {
			return true
		}
	}
	return false
}

func (h *captureHook) findField(message, field string) (interface{}, bool) {
	h.mu.Lock()
	defer h.mu.Unlock()
	for _, r := range h.records {
		if r.message == message {
			v, ok := r.fields[field]
			return v, ok
		}
	}
	return nil, false
}

func newTestExecutor(t *testing.T) (*Executor, *captureHook) {
	t.Helper()
	hook := &captureHook{}
	log := logrus.New()
	log.SetOutput(io.Discard)
	log.SetLevel(logrus.DebugLevel)
	log.AddHook(hook)
	return New(log), hook
}

