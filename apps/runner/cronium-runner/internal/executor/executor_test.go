// setupScript prepares a work dir with a stub discovery script (the real one
// is generated by SetupHelpers) plus the entrypoint, and returns an executor
// wired to run it via executeScript.
func setupScript(t *testing.T, interpreter types.ScriptType, entrypoint, script string) (*Executor, *captureHook) {
	t.Helper()
	e, hook := newTestExecutor(t)
	workDir := t.TempDir()
	croniumDir := filepath.Join(workDir, ".cronium")
	if err := os.MkdirAll(croniumDir, 0o755); err != nil {
		t.Fatalf("failed to create .cronium dir: %v", err)
	}
	stubs := map[string]string{
		"discovery.sh": "#!/bin/bash\n",
		"discovery.py": "",
		"discovery.js": "",
	}
	for name, content := range stubs {
		if err := os.WriteFile(filepath.Join(croniumDir, name), []byte(content), 0o755); err != nil {
			t.Fatalf("failed to write %s stub: %v", name, err)
		}
	}
	if script != "" {
		if err := os.WriteFile(filepath.Join(workDir, entrypoint), []byte(script), 0o755); err != nil {
			t.Fatalf("failed to write entrypoint: %v", err)
		}
	}
	e.workDir = workDir
	e.manifest = &types.Manifest{
		Version:     "v1",
		Interpreter: interpreter,
		Entrypoint:  entrypoint,
	}
	return e, hook
}

// runWithWatchdog runs executeScript and fails fast if it does not return —
// the regression mode of the long-line bug was an indefinite hang.
func runWithWatchdog(t *testing.T, e *Executor, timeout time.Duration) error {
	t.Helper()
	done := make(chan error, 1)
	go func() { done <- e.executeScript() }()
	select {
	case err := <-done:
		return err
	case <-time.After(timeout):
		t.Fatalf("executeScript did not return within %v (hung child process?)", timeout)
		return nil
	}
}

func TestExecuteScriptExitZeroCapturesBothStreams(t *testing.T) {
	requireTool(t, "bash")
	e, hook := setupScript(t, types.ScriptTypeBash, "script.sh", `
echo out-line-1
echo out-line-2
echo err-line-1 1>&2
`)

	if err := runWithWatchdog(t, e, 10*time.Second); err != nil {
		t.Fatalf("expected exit 0, got: %v", err)
	}

	stdout := hook.streamLines("stdout")
	// Per-stream ordering is pinned; interleaving across streams is not
	// deterministic (two goroutines) and deliberately not asserted.
	want := []string{"out-line-1", "out-line-2"}
	if len(stdout) != len(want) || stdout[0] != want[0] || stdout[1] != want[1] {
		t.Errorf("stdout lines = %#v, want %#v", stdout, want)
	}
	stderr := hook.streamLines("stderr")
	if len(stderr) != 1 || stderr[0] != "err-line-1" {
		t.Errorf("stderr lines = %#v, want [err-line-1]", stderr)
	}
}

